import nltk
import pandas as pd

from nltk.tokenize import word_tokenize
from nltk.corpus import stopwords
from sklearn.feature_extraction.text import CountVectorizer

nltk.download("punkt_tab", quiet=True)
nltk.download("stopwords", quiet=True)

documents = [
    "The girl bought a chocolate",
    "The boy ate the chocolate",
    "The girl bought a toy",
    "The girl played with the toy"
]

# 1. Text Preprocessing
stop_words = set(stopwords.words("english"))

def preprocess(doc):
    return [
        word for word in word_tokenize(doc.lower())
        if word.isalpha() and word not in stop_words
    ]

processed = [preprocess(doc) for doc in documents]

print("PROCESSED DOCUMENTS")

for doc in processed:
    print(doc)

# 2. Vocabulary Creation
vocabulary = sorted(set(word for doc in processed for word in doc))

print("\nVOCABULARY:")
print(vocabulary)

# 3. Manual Bag of Words
vectors = [
    [doc.count(word) for word in vocabulary]
    for doc in processed
]

df = pd.DataFrame(
    vectors,
    columns=vocabulary,
    index=["Doc 1", "Doc 2", "Doc 3", "Doc 4"]
)

print("\nMANUAL DOCUMENT TERM MATRIX:")
print(df)

# 4. Bag of Words using CountVectorizer
cv = CountVectorizer(stop_words="english")

X = cv.fit_transform(documents)

df2 = pd.DataFrame(
    X.toarray(),
    columns=cv.get_feature_names_out(),
    index=df.index
)

print("\nSCIKIT-LEARN DOCUMENT TERM MATRIX:")
print(df2)

print("\nBoth Matrices are Same:", df.equals(df2))

# 5. Weakness of Bag of Words
a = "The girl bought the toy"
b = "The toy bought the girl"

cv2 = CountVectorizer()

vectors = cv2.fit_transform([a, b]).toarray()

print("\nWORD ORDER EXAMPLE:")
print(vectors)

print("Same Vector:", (vectors[0] == vectors[1]).all())

